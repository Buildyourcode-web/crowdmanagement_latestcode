const STATUSES = ["online", "online", "online", "online", "online", "online", "online", "online", "online", "offline", "degraded"];
const RESOLUTIONS = ["1920x1080", "3840x2160", "1280x720", "2560x1440"];
const GPU_UNITS = ["GPU-01", "GPU-02", "GPU-03", "GPU-04"];

function rand(min, max) {
  return Math.floor(Math.random() * (max - min + 1)) + min;
}

export const CAMERAS = CAMERA_LOCATIONS.map((loc, i) => {
  const id = String(i + 1).padStart(3, "0");
  const statusIdx = i === 41 || i === 67 || i === 83 ? 10 : i === 22 || i === 55 ? 9 : Math.floor(Math.random() * 9);
  const status = STATUSES[statusIdx] || "online";
  const isOnline = status === "online";
  const isDegraded = status === "degraded";

  return {
    id: `CAM-KHB-${id}`,
    name: `CAM-KHB-${id}`,
    label: loc.label,
    zone: loc.zone,
    status,
    fps: isOnline ? rand(22, 30) : isDegraded ? rand(8, 15) : 0,
    latency: isOnline ? rand(28, 65) : isDegraded ? rand(100, 250) : null,
    packetLoss: isOnline ? (Math.random() * 2).toFixed(1) : isDegraded ? (2 + Math.random() * 8).toFixed(1) : null,
    resolution: RESOLUTIONS[i % RESOLUTIONS.length],
    aiStatus: isOnline ? (i % 12 === 0 ? "degraded" : "online") : "offline",
    gpuUnit: GPU_UNITS[i % GPU_UNITS.length],
    inferenceMs: isOnline ? rand(22, 55) : null,
    peopleCount: isOnline ? rand(100, 1800) : 0,
    queueCount: isOnline ? rand(0, 450) : 0,
    density: isOnline ? (Math.random() * 8).toFixed(1) : 0,
    isFRS: i < 15,
    frsStatus: i < 15 ? (isOnline ? "online" : "offline") : null,
    lastSeen: isOnline ? "LIVE" : `${rand(1, 30)} min ago`,
    rtsp: isOnline ? `rtsp://mock-stream/${id}` : null,
    alerts: i === 11 || i === 14 ? ["crowd_density"] : [],
    coordinates: [
      78.4635 + (i % 30) * 0.0008,
      17.4175 + Math.floor(i / 30) * 0.0025,
    ],
  };
});

